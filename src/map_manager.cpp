static std::vector<sf::Texture> tilesets;

void loadTilesets() {
    // Tránh load lại nếu đã load rồi
    if (!tilesets.empty()) return;

    const char* paths[] = {
        "assets/tilesets/snow_dirt_01.png",
        "assets/tilesets/snow_dirt_02.png",
        "assets/tilesets/snow_dirt_03.png",
        "assets/tilesets/snow_dirt_04.png",
        "assets/tilesets/snow_dirt_05.png",
    };

    for (const char* path : paths) {
        sf::Texture tex;
        if (tex.loadFromFile(path)) {
            tilesets.push_back(std::move(tex));
        } else {
            std::cerr << "Không thể load tileset: " << path << "\n";
        }
    }
}

void drawMap(sf::RenderWindow& window) {
    // Tính hệ số scale để ảnh tile vừa khít TILE_SIZE x TILE_SIZE pixel
    for (int y = 0; y < MAP_HEIGHT; ++y) {
        for (int x = 0; x < MAP_WIDTH; ++x) {
            int tileID = mapData[y][x];
            if (tileID <= 0) continue; // 0 = không khí

            int texIndex = tileID - 1; // tileID 1 → tilesets[0], v.v.
            if (texIndex >= static_cast<int>(tilesets.size())) continue;

            const sf::Texture& tex = tilesets[texIndex];
            sf::Vector2u texSize = tex.getSize();

            sf::Sprite sprite(tex);

            // Scale để tile vừa đúng TILE_SIZE x TILE_SIZE
            float scaleX = static_cast<float>(TILE_SIZE) / texSize.x;
            float scaleY = static_cast<float>(TILE_SIZE) / texSize.y;
            sprite.setScale(sf::Vector2f(scaleX, scaleY));

            sprite.setPosition(sf::Vector2f(
                static_cast<float>(x * TILE_SIZE),
                static_cast<float>(y * TILE_SIZE)
            ));

            window.draw(sprite);
        }
    }
}